// Generates CSS custom properties from tokens/m3.json:
//   node scripts/tokens.ts <out.css>
// A design change is a change to the JSON, never to the CSS.

import { readFileSync, writeFileSync } from 'node:fs'
import {
  argbFromHex,
  DynamicScheme,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  SchemeExpressive,
  SchemeTonalSpot,
  SchemeVibrant
} from '@material/material-color-utilities'

type TypeStyle = {
  typeface: 'brand' | 'plain'
  size: number
  lineHeight: number
  weight: number
  tracking: number
}

export type TokenSource = {
  color: {
    seed: string
    variant: 'tonal-spot' | 'expressive' | 'vibrant'
    specVersion: '2021' | '2025'
    contrast: number
  }
  typeface: { brand: string; plain: string }
  typescale: Record<string, TypeStyle>
  shape: Record<string, number>
}

const schemes = {
  'tonal-spot': SchemeTonalSpot,
  expressive: SchemeExpressive,
  vibrant: SchemeVibrant
}

const rem = (px: number) => `${px / 16}rem`
const kebab = (name: string) => name.replaceAll('_', '-')

export function colorRoles(
  source: TokenSource,
  dark: boolean
): Record<string, string> {
  const { seed, variant, specVersion, contrast } = source.color
  const scheme: DynamicScheme = new schemes[variant](
    Hct.fromInt(argbFromHex(seed)),
    dark,
    contrast,
    specVersion
  )
  const colors = new MaterialDynamicColors()
  const roles: Record<string, string> = {}
  for (const color of [...colors.allColors, colors.shadow(), colors.scrim()]) {
    roles[kebab(color.name)] = hexFromArgb(color.getArgb(scheme))
  }
  return roles
}

function block(selector: string, props: Record<string, string>): string {
  const lines = Object.entries(props).map(([k, v]) => `  ${k}: ${v};`)
  return `${selector} {\n${lines.join('\n')}\n}\n`
}

function colorProps(roles: Record<string, string>): Record<string, string> {
  return Object.fromEntries(
    Object.entries(roles).map(([name, hex]) => [`--md-sys-color-${name}`, hex])
  )
}

export function buildCss(source: TokenSource): string {
  const base: Record<string, string> = {
    'color-scheme': 'light dark',
    '--md-ref-typeface-brand': source.typeface.brand,
    '--md-ref-typeface-plain': source.typeface.plain
  }
  for (const [name, style] of Object.entries(source.typescale)) {
    const p = `--md-sys-typescale-${name}`
    base[`${p}-font`] = `var(--md-ref-typeface-${style.typeface})`
    base[`${p}-size`] = rem(style.size)
    base[`${p}-line-height`] = rem(style.lineHeight)
    base[`${p}-weight`] = String(style.weight)
    base[`${p}-tracking`] = rem(style.tracking)
  }
  for (const [name, px] of Object.entries(source.shape)) {
    base[`--md-sys-shape-${name}`] = `${px}px`
  }

  const light = colorProps(colorRoles(source, false))
  const dark = colorProps(colorRoles(source, true))
  return [
    '/* Generated by scripts/tokens.ts from tokens/m3.json. Do not edit. */\n',
    block(':root', { ...base, ...light }),
    `@media (prefers-color-scheme: dark) {\n${block(":root:not([data-theme='light'])", dark).replace(/^/gm, '  ').trimEnd()}\n}\n`,
    block(":root[data-theme='dark']", dark)
  ].join('\n')
}

export function readSource(): TokenSource {
  return JSON.parse(
    readFileSync(new URL('../tokens/m3.json', import.meta.url), 'utf8')
  ) as TokenSource
}

if (import.meta.main) {
  const out = process.argv[2]
  if (!out) {
    console.error('usage: node scripts/tokens.ts <out.css>')
    process.exit(2)
  }
  writeFileSync(out, buildCss(readSource()))
}
